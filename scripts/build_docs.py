"""Build the published documents from templates.

Usage: python scripts/build_docs.py [--check]

1. Rebuilds results/headline.json from the results files (scripts/headline.py).
2. Fills every {{RESULT:...}} token in docs/src/*.md (scripts/fill_docs.py) and writes the
   README to the repository root and every other template to docs/.
3. Fails if a token cannot be resolved or any {{...}} placeholder remains.
Edit the templates in docs/src/, never the generated files.
"""

from __future__ import annotations

import argparse
import sys

from aerialrange.utils.config import REPO_ROOT

sys.path.insert(0, str(REPO_ROOT / "scripts"))
import headline  # noqa: E402
from fill_docs import fill, unresolved  # noqa: E402

SRC = REPO_ROOT / "docs" / "src"
PREVIEW = REPO_ROOT / "cache" / "docs_preview"
# Banned filler phrases (case-insensitive); "state-of-the-art" is allowed only with a
# specific comparison, so it is flagged for a human look rather than refused.
BANNED = (
    "delve",
    "in today's rapidly evolving",
    "it is important to note",
    "leverage",
    "cutting-edge",
    "seamless",
    "game-changer",
    "robust solution",
    "in conclusion",
    "furthermore",
    "moreover",
    "state-of-the-art",
)
HEADER = "<!-- Generated by scripts/build_docs.py from docs/src/{name}; edit the template. -->\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="only check that templates fill")
    args = ap.parse_args(argv)
    # call, not run as __main__: its sys.exit would end this script before any template
    # was checked (a bug that made earlier checks pass vacuously)
    if headline.main() != 0:
        print("headline.json could not be built")
        return 1
    bad = 0
    for src in sorted(SRC.glob("*.md")):
        text = fill(src.read_text(encoding="utf-8"))
        hits = [b for b in BANNED if b in text.lower()]
        if hits:
            print(f"{src.name}: banned phrases {hits}")
            bad += 1
        left = unresolved(text)
        if left:
            print(f"{src.name}: unresolved {left}; preview in cache/docs_preview/")
            PREVIEW.mkdir(parents=True, exist_ok=True)
            (PREVIEW / src.name).write_text(text, encoding="utf-8")
            bad += 1
            continue
        dest = REPO_ROOT / "README.md" if src.name == "README.md" else REPO_ROOT / "docs" / src.name
        if not args.check:
            dest.write_text(HEADER.format(name=src.name) + text, encoding="utf-8")
            print(f"wrote {dest.relative_to(REPO_ROOT)}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
