"""AU-AIR contact sheets and clip notes for the author's tilt labels.

Usage: python scripts/contact_sheets.py

For each clip in cache/auair/frames.csv (scripts/auair_frames.py), 12 frames spread evenly in
time are tiled 4 x 3, each labelled with frame index, altitude and the two small angles. Sheets
go to cache/auair/contact_sheets/clip_NN.jpg: they are made of AU-AIR images and are not
committed (D-323). docs/auair_clip_notes.md lists each clip's altitude profile and attitude
statistics, with empty columns for the manual labels (straight-down or oblique, lens curvature).
"""

from __future__ import annotations

import sys

import cv2
import numpy as np
import pandas as pd

from aerialrange.utils.config import REPO_ROOT, load_config

COLS, ROWS, TILE_W = 4, 3, 480


def _tile(img: np.ndarray, lines: list[str]) -> np.ndarray:
    h = round(img.shape[0] * TILE_W / img.shape[1])
    t = cv2.resize(img, (TILE_W, h), interpolation=cv2.INTER_AREA)
    for i, s in enumerate(lines):
        y = 22 + 22 * i
        cv2.putText(t, s, (8, y), cv2.FONT_HERSHEY_SIMPLEX, 0.55, (0, 0, 0), 4, cv2.LINE_AA)
        cv2.putText(t, s, (8, y), cv2.FONT_HERSHEY_SIMPLEX, 0.55, (255, 255, 255), 1, cv2.LINE_AA)
    return t


def main() -> int:
    cfg = load_config("data")
    root = REPO_ROOT / cfg.require("data_root") / cfg.require("auair_subdir")
    df = pd.read_csv(REPO_ROOT / "cache" / "auair" / "frames.csv", dtype={"recording": str})
    out = REPO_ROOT / "cache" / "auair" / "contact_sheets"
    out.mkdir(parents=True, exist_ok=True)
    notes = []
    for clip, g in df.groupby("clip"):
        g = g.sort_values("t_ms")
        pick = g.iloc[np.unique(np.linspace(0, len(g) - 1, COLS * ROWS).round().astype(int))]
        tiles = []
        for _, r in pick.iterrows():
            img = cv2.imread(str(root / r["image_path"]))
            tiles.append(
                _tile(
                    img,
                    [
                        f"clip {clip}  frame {r['index']}  part {r['part']}",
                        f"alt {r['alt_m']:.1f} m  t {r['t_ms'] / 1000:.1f} s",
                        f"phi {np.degrees(r['angle_phi']):+.1f}  theta "
                        f"{np.degrees(r['angle_theta']):+.1f} deg",
                    ],
                )
            )
        blank = np.zeros_like(tiles[0])
        tiles += [blank] * (COLS * ROWS - len(tiles))
        sheet = np.vstack([np.hstack(tiles[i : i + COLS]) for i in range(0, len(tiles), COLS)])
        cv2.imwrite(str(out / f"clip_{clip:02d}.jpg"), sheet, [cv2.IMWRITE_JPEG_QUALITY, 85])
        deg = np.degrees
        notes.append(
            f"| {clip} | {g['recording'].iloc[0]} | {len(g)} | "
            f"{(g['t_ms'].max() - g['t_ms'].min()) / 1000:.0f} | "
            f"{g['alt_m'].min():.1f} / {g['alt_m'].median():.1f} / {g['alt_m'].max():.1f} | "
            f"{deg(g['angle_phi']).median():+.1f} ({deg(g['angle_phi']).std():.1f}) | "
            f"{deg(g['angle_theta']).median():+.1f} ({deg(g['angle_theta']).std():.1f}) | "
            f"`clip_{clip:02d}.jpg` |  |  |"
        )
        print(f"clip {clip}: {len(pick)} tiles", flush=True)
    md = [
        "# AU-AIR clip notes",
        "",
        "Generated by `scripts/contact_sheets.py` from `cache/auair/frames.csv`. Clips are "
        "split where frames are more than 6 s apart (D-502). Angles are the file's "
        "`angle_phi` and `angle_theta` in degrees, median (standard deviation); which is roll "
        "and which is pitch is not yet resolved. Contact sheets are in "
        "`cache/auair/contact_sheets/` (not committed: AU-AIR images, D-323).",
        "",
        "**Labels** (filled by hand from the sheets): **View**: `down` "
        "(camera looks straight down), `oblique` (camera looks forward at an angle; a "
        "rough angle below the horizon, where 0 = looking at the horizon, "
        "90 = straight down, so `oblique ~45` is halfway), or `mixed` "
        "(the view changes within the clip). **Curvature**: `yes` if straight lines (road "
        "edges, markings) bend near the image edges, otherwise `no`.",
        "",
        "| Clip | Recording | Frames | Duration (s) | Altitude min / median / max (m) "
        "| phi (deg) | theta (deg) | Sheet | View | Curvature |",
        "|---|---|---|---|---|---|---|---|---|---|",
        *notes,
        "",
    ]
    (REPO_ROOT / "docs" / "auair_clip_notes.md").write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {len(notes)} sheets to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
